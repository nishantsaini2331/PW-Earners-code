let num = 16;

if (num % 2 === 0) {
    console.log("Even number");
} else {
    console.log("Odd number");
}

if (num > 0) {
    console.log("Positive Number");
} else if (num < 0) {
    console.log("Negative Number");
} else {
    console.log("Zero");
}

if (num > 100) {
    console.log("Greater than 100");
} else if (num < 100) {
    console.log("Less than 100");
} else {
    console.log("Equal to 100");
}